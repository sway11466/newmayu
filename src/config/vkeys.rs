pub fn vk_by_name(name: &str) -> Option<u8> {
    VKEYS
        .iter()
        .find(|(n, _)| n.eq_ignore_ascii_case(name))
        .map(|(_, v)| *v)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_resolve_case_insensitively() {
        assert_eq!(vk_by_name("RButton"), Some(0x02));
        assert_eq!(vk_by_name("lbutton"), Some(0x01));
        assert_eq!(vk_by_name("_0"), Some(0x30));
        assert_eq!(vk_by_name("z"), Some(0x5a));
        assert_eq!(vk_by_name("DBE_HIRAGANA"), Some(0xf2));
        assert_eq!(vk_by_name("Nothing"), None);
    }
}
